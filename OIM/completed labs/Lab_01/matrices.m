%% Лабораторная работа 1. Часть 1. Матрицы
% Матрицы выводятся последовательно; исходные A и B сохраняются.
A = [22 5; 4 11; 13 2]
B = [17 9 2 1 3; 6 4 11 9 16]
C = eye(3)
%% Изменение A, умножение на скаляр и транспонирование
D = A - [0 0; 3 0; 0 0]
E = 3 * D
F = D.'
%% Изменение третьего столбца и выбор столбцов в обратном порядке
G = B;
G(:,3) = G(:,3) + [1; -8];
G
H = G(:,5:-2:1)
%% Подматрица единичной матрицы и смена знака второго столбца
I = C(1:2,1:2)
J = I * diag([1 -1])
K = D * J
assert(isequal(E,[66 15;3 33;39 6]));
assert(isequal(F,[22 1 13;5 11 2]));
assert(isequal(H,[3 3 17;16 3 6]));
assert(isequal(K,[22 -5;1 -11;13 -2]));
